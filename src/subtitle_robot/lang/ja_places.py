"""굳어진 일본 지명 표기 사전 (PROJECT-PLAN §8.5, WI-2.007).

음역 스타일과 무관하게 국내에서 굳어진 표기를 쓴다 (東京 → 도쿄, 千葉 → 지바). 출처는 `generated`.
표기는 국립국어원 외래어 표기법 용례와 언론 관용을 따른다. 작품 고유 지명은 여기에 넣지 않는다.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class PlaceName:
    """지명 하나."""

    source: str
    reading: str
    ko: str


CONVENTIONAL_PLACES: tuple[PlaceName, ...] = tuple(
    PlaceName(source, reading, ko)
    for source, reading, ko in (
        ("日本", "にほん", "일본"),
        ("東京", "とうきょう", "도쿄"),
        ("大阪", "おおさか", "오사카"),
        ("京都", "きょうと", "교토"),
        ("北海道", "ほっかいどう", "홋카이도"),
        ("本州", "ほんしゅう", "혼슈"),
        ("九州", "きゅうしゅう", "규슈"),
        ("四国", "しこく", "시코쿠"),
        ("沖縄", "おきなわ", "오키나와"),
        ("横浜", "よこはま", "요코하마"),
        ("名古屋", "なごや", "나고야"),
        ("神戸", "こうべ", "고베"),
        ("福岡", "ふくおか", "후쿠오카"),
        ("広島", "ひろしま", "히로시마"),
        ("札幌", "さっぽろ", "삿포로"),
        ("仙台", "せんだい", "센다이"),
        ("長崎", "ながさき", "나가사키"),
        ("奈良", "なら", "나라"),
        ("鎌倉", "かまくら", "가마쿠라"),
        ("千葉", "ちば", "지바"),
        ("埼玉", "さいたま", "사이타마"),
        ("静岡", "しずおか", "시즈오카"),
        ("金沢", "かなざわ", "가나자와"),
        ("熊本", "くまもと", "구마모토"),
        ("鹿児島", "かごしま", "가고시마"),
        ("新宿", "しんじゅく", "신주쿠"),
        ("渋谷", "しぶや", "시부야"),
        ("池袋", "いけぶくろ", "이케부쿠로"),
        ("秋葉原", "あきはばら", "아키하바라"),
        ("原宿", "はらじゅく", "하라주쿠"),
        ("浅草", "あさくさ", "아사쿠사"),
        ("品川", "しながわ", "시나가와"),
        ("上野", "うえの", "우에노"),
        ("銀座", "ぎんざ", "긴자"),
        ("富士山", "ふじさん", "후지산"),
    )
)
_BY_SOURCE = {place.source: place for place in CONVENTIONAL_PLACES}


def lookup_place(source: str) -> PlaceName | None:
    """원문 표기(한자)로 지명을 찾는다. 읽기가 같은 다른 단어와 섞이지 않도록 한자로만 찾는다."""
    return _BY_SOURCE.get(source.strip())
